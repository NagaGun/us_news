/**
 * Calculates raw category scores for a given hospital metrics object and department.
 */
export function calculateHospitalCategoryScores(metrics: { [metricId: string]: number }) {
  const categorySums: { [category: string]: { weightedScore: number; totalWeight: number } } = {
    Outcome: { weightedScore: 0, totalWeight: 0 },
    Structure: { weightedScore: 0, totalWeight: 0 },
    Process: { weightedScore: 0, totalWeight: 0 },
    'Patient Exp': { weightedScore: 0, totalWeight: 0 },
  };

  METRIC_DEFINITIONS.forEach((metric: MetricDefinition) => {
    const rawVal = metrics[metric.id] ?? metric.min;
    // Normalize to 0-100 score
    const { min, max } = metric;
    let normScore = 50;
    if (max > min) {
      normScore = Math.max(0, Math.min(100, ((rawVal - min) / (max - min)) * 100));
    }

    const cat = categorySums[metric.category];
    if (cat) {
      cat.weightedScore += normScore * (metric.weightInCategory / 100);
      cat.totalWeight += metric.weightInCategory;
    }
  });

  const categoryScores: { [category: string]: number } = {
    Overall: 0,
    Outcome: 0,
    Structure: 0,
    Process: 0,
    'Patient Exp': 0,
  };

  Object.keys(categorySums).forEach((catKey) => {
    const info = categorySums[catKey];
    categoryScores[catKey] = Math.round(info.weightedScore);
  });

  // Calculate Overall Composite (0-100)
  const composite = Math.round(
    (categoryScores.Outcome * CATEGORY_WEIGHTS.Outcome +
      categoryScores.Structure * CATEGORY_WEIGHTS.Structure +
      categoryScores.Process * CATEGORY_WEIGHTS.Process +
      categoryScores['Patient Exp'] * CATEGORY_WEIGHTS['Patient Exp']) /
      100
  );

  categoryScores.Overall = composite;

  return categoryScores;
}
